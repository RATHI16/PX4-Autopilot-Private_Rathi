/* ---------------------------------------------------------------------------
   Function implementations
   --------------------------------------------------------------------------- */

void ssd1309_draw_char(uint8_t x, uint8_t y, char c, uint8_t color, uint8_t size)
{
    if (c < 32 || c > 122) return;
    const uint8_t *glyph = font5x7[(uint8_t)c - 32];

    for (uint8_t col = 0; col < 5; col++)
    {
        uint8_t bits = glyph[col];
        for (uint8_t row = 0; row < 8; row++)
        {
            if (bits & 0x01)
            {
                for (uint8_t sx = 0; sx < size; sx++)
                {
                    for (uint8_t sy = 0; sy < size; sy++)
                    {
                        ssd1309_draw_pixel(x + col * size + sx,
                                           y + row * size + sy, color);
                    }
                }
            }
            bits >>= 1;
        }
    }
}

void ssd1309_draw_string(uint8_t x, uint8_t y, const char *str,
                         uint8_t color, uint8_t size)
{
    uint8_t cursor_x = x;
    while (*str)
    {
        if (*str == '\n')
        {
            cursor_x = x;
            y += 8u * size;
        }
        else if (*str == '\r')
        {
            cursor_x = x;
        }
        else
        {
            ssd1309_draw_char(cursor_x, y, *str, color, size);
            cursor_x += 6u * size;
            if ((uint16_t)cursor_x + 6u * size > SSD1309_WIDTH)
            {
                cursor_x = x;
                y += 8u * size;
            }
        }
        str++;
    }
}

void ssd1309_draw_hline(uint8_t x, uint8_t y, uint8_t w, uint8_t color)
{
    for (uint8_t i = 0; i < w; i++)
        ssd1309_draw_pixel(x + i, y, color);
}

void ssd1309_draw_vline(uint8_t x, uint8_t y, uint8_t h, uint8_t color)
{
    for (uint8_t i = 0; i < h; i++)
        ssd1309_draw_pixel(x, y + i, color);
}

void ssd1309_draw_rect(uint8_t x, uint8_t y, uint8_t w, uint8_t h,
                       uint8_t color)
{
    ssd1309_draw_hline(x,         y,         w, color);
    ssd1309_draw_hline(x,         y + h - 1, w, color);
    ssd1309_draw_vline(x,         y,         h, color);
    ssd1309_draw_vline(x + w - 1, y,         h, color);
}

void ssd1309_fill_rect(uint8_t x, uint8_t y, uint8_t w, uint8_t h,
                       uint8_t color)
{
    for (uint8_t r = 0; r < h; r++)
        ssd1309_draw_hline(x, y + r, w, color);
}
